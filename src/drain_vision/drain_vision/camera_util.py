#!/usr/bin/env python3
# =============================================================================
#  camera_util — 카메라 장치 지정을 한 곳에서 해석한다
# =============================================================================
#  ★ 왜 번호를 쓰면 안 되는가 ★
#    /dev/videoN 의 N 은 **USB 열거 순서**로 정해진다. 재부팅·재연결·허브 순서에
#    따라 바뀐다. 이 로봇에는 카메라가 두 대다 —
#        C270 = 앞(탐지)   ·   C920 = 뒤(캡쳐)
#    번호로 잡으면 어느 날 **앞 카메라를 후방 캡쳐로 찍는다.** 사진은 남지만
#    엉뚱한 사진이라 **틀렸다는 것조차 서버에서 알 수 없다.**
#
#    /dev/v4l/by-id/ 의 이름은 **장치가 스스로 보고하는 모델명·일련번호**로
#    만들어지므로 순서가 바뀌어도 같은 카메라를 가리킨다.
#        $ ls /dev/v4l/by-id/
#    ※ 웹캠은 대개 index0(영상) / index1(메타데이터) 둘을 만든다. **index0** 을 쓸 것.
#    ※ 카메라를 다른 개체로 바꾸면 일련번호가 달라진다. 그때는 다시 확인할 것.
#
#  ★ 문자열 경로에는 백엔드를 명시해야 한다 ★
#    cv2.VideoCapture("/dev/video0") 처럼 **파일명으로 주면** OpenCV 가 FFMPEG 같은
#    다른 백엔드를 먼저 물 수 있다. 정수로 줄 때는 V4L2 가 잡히던 것이 경로로 바꾸는
#    순간 달라진다. 그래서 경로일 때는 cv2.CAP_V4L2 를 함께 넘긴다.
# =============================================================================

import cv2


def as_device(value):
    """파라미터 값을 VideoCapture 인자로 바꾼다.

    "0" 같은 정수 문자열은 정수로, 그 외에는 경로 문자열로 준다.
    (옛 설정 파일이 정수를 그대로 갖고 있어도 계속 돌아가야 한다)
    """
    s = str(value)
    return int(s) if s.isdigit() else s


def open_capture(device):
    """장치를 연다. 경로면 V4L2 백엔드를 명시한다."""
    if isinstance(device, str):
        return cv2.VideoCapture(device, cv2.CAP_V4L2)
    return cv2.VideoCapture(device)
